/** Icons for the whole app. They keep the names the code already uses and are drawn by Iconoir. */
export type LucideIcon = React.ComponentType<{ size?: number | string; strokeWidth?: number | string; className?: string; style?: React.CSSProperties; fill?: string; 'aria-hidden'?: boolean | 'true' | 'false' }>

type P = { size?: number | string; strokeWidth?: number | string; className?: string; style?: React.CSSProperties; fill?: string; 'aria-hidden'?: boolean | 'true' | 'false' }
const wrap = (C: React.ComponentType<React.SVGProps<SVGSVGElement>>): LucideIcon => function Icon({ size = 24, strokeWidth = 1.75, ...p }: P) {
  return <C width={size} height={size} strokeWidth={strokeWidth} {...p} />
}

