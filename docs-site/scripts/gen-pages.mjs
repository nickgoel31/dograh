function write(rel, fm, body) {
  const file = join(root, 'src/content/docs', rel);
  mkdirSync(dirname(file), { recursive: true });
  const head = Object.entries({ ...fm, lastUpdated: undefined })
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `${k}: ${typeof v === 'string' ? JSON.stringify(v) : JSON.stringify(v)}`)
    .join('\n');
  writeFileSync(file, `---\n${head}\n---\n{/* GENERATED by scripts/gen-pages.mjs from the product code. Do not edit by hand. */}\n\n${body.trim()}\n`);
}
